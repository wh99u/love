// Builds src/ui/icons.gen.ts from Phosphor Icons (MIT, https://phosphoricons.com).
// Run: node scripts/icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '../node_modules/@phosphor-icons/core/assets');

// app name → [phosphor name, weights]
const MAP = {
  wallet: ['wallet', 'regular fill'],
  car: ['car-profile', 'regular fill'],
  bag: ['shopping-bag', 'regular fill'],
  calendar: ['calendar-dots', 'regular fill'],
  plus: ['plus', 'regular bold'],
  transfer: ['arrows-left-right', 'regular'],
  pie: ['chart-pie-slice', 'regular fill'],
  bolt: ['lightning', 'regular fill'],
  card: ['credit-card', 'regular'],
  search: ['magnifying-glass', 'regular'],
  bell: ['bell-simple', 'regular'],
  chevron: ['caret-right', 'regular bold'],
  back: ['caret-left', 'regular bold'],
  down: ['caret-down', 'regular bold'],
  copy: ['copy', 'regular'],
  trash: ['trash', 'regular'],
  edit: ['pencil-simple', 'regular'],
  check: ['check', 'regular bold'],
  close: ['x', 'regular bold'],
  photo: ['image', 'regular'],
  link: ['link-simple', 'regular bold'],
  sparkle: ['sparkle', 'fill'],
  coins: ['coins', 'regular'],
  clock: ['clock', 'regular'],
  trend: ['trend-up', 'regular'],
  flag: ['flag', 'regular'],
  list: ['list-bullets', 'regular'],
  users: ['users', 'regular fill'],
  share: ['paper-plane-tilt', 'regular fill'],
  cloud: ['cloud-check', 'regular'],
  cloudOff: ['cloud-slash', 'regular'],
  sync: ['arrows-clockwise', 'regular bold'],
  key: ['key', 'regular'],
  signOut: ['sign-out', 'regular'],
  tag: ['tag', 'regular'],
  backspace: ['backspace', 'regular'],
  // budget categories (names are stored in the data)
  home: ['house', 'regular fill'],
  food: ['fork-knife', 'regular fill'],
  bus: ['bus', 'regular fill'],
  phone: ['device-mobile', 'regular fill'],
  fun: ['ticket', 'regular fill'],
  health: ['heart', 'regular fill'],
  gift: ['gift', 'regular fill'],
  // shifts
  sun: ['sun', 'fill'],
  moon: ['moon', 'fill'],
};

const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<rect width="256" height="256" fill="none"\/>/g, '').trim();

const out = { regular: {}, bold: {}, fill: {} };
for (const [name, [ph, weights]] of Object.entries(MAP)) {
  for (const w of weights.split(' ')) {
    const file = w === 'regular' ? `${ph}.svg` : `${ph}-${w}.svg`;
    out[w][name] = inner(readFileSync(join(root, w, file), 'utf8'));
  }
}

const block = (o) => Object.entries(o).map(([k, v]) => `  ${/^[a-z]\w*$/i.test(k) ? k : `'${k}'`}: '${v.replace(/'/g, "\\'")}',`).join('\n');
writeFileSync(
  'src/ui/icons.gen.ts',
  `// Generated by scripts/icons.mjs from Phosphor Icons (MIT). Do not edit by hand.
/* eslint-disable */
export const REGULAR: Record<string, string> = {
${block(out.regular)}
};
export const BOLD: Record<string, string> = {
${block(out.bold)}
};
export const FILL: Record<string, string> = {
${block(out.fill)}
};
`,
);
console.log('icons:', Object.keys(MAP).length);
