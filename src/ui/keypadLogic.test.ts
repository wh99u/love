import { expect, test } from 'vitest';
import { keypadReduce } from './keypadLogic';

test.each([
  ['', '0', ''],
  ['5', '0', '50'],
  ['5', '000', '5000'],
  ['', '000', ''],
  ['123', '⌫', '12'],
  ['', '⌫', ''],
  ['100000000', '0', '1000000000'],
  ['999999999', '9', '999999999'],
  ['1000000', '000', '1000000000'],
  ['10000000', '000', '10000000'],
  ['12', 'x', '12'],
])('%s + %s → %s', (value, key, out) => {
  expect(keypadReduce(value, key)).toBe(out);
});
